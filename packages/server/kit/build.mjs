// Builds the dashboard kit's page: page.src.html with
// ECharts put in (only what the kit draws: line and bar; grid, legend, tooltip; the SVG renderer), written to
// ../src/dashboardKitPage.ts as a string the server carries (no file to find at run time, packaged or not).
//
// Run it after changing page.src.html, from a folder that has esbuild and echarts installed (they aren't the
// workspace's own yet):   node <repo>/packages/server/kit/build.mjs [preview.html [sample.json]]
// With a preview path it also writes the page on its own (with the sample's data in it, when given) to look at.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const lib = await build({
  stdin: {
    contents: `import * as echarts from 'echarts/core'; import { BarChart, LineChart } from 'echarts/charts'; import { GridComponent, LegendComponent, TooltipComponent } from 'echarts/components'; import { SVGRenderer } from 'echarts/renderers'; echarts.use([BarChart, LineChart, GridComponent, LegendComponent, TooltipComponent, SVGRenderer]); window.echarts = echarts;`,
    resolveDir: process.cwd(),
  },
  bundle: true, minify: true, format: 'iife', write: false, logLevel: 'error', charset: 'ascii',
});
const js = lib.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const page = readFileSync(join(here, 'page.src.html'), 'utf8').replace(/\r\n/g, '\n').replace('<script>/*ECHARTS*/</script>', () => `<script>${js}</script>`);
writeFileSync(
  join(here, '..', 'src', 'dashboardKitPage.ts'),
  `// GENERATED by packages/server/kit/build.mjs from kit/page.src.html: don't edit it here.\n/* eslint-disable */\n/** The dashboard kit's page: what Cora writes as a kit dashboard's page.html. */\nexport const DASHBOARD_KIT_PAGE: string = ${JSON.stringify(page)};\n`,
);
if (process.argv[2]) {
  let out = page;
  if (process.argv[3]) {
    const data = JSON.stringify(JSON.parse(readFileSync(process.argv[3], 'utf8'))).replace(/</g, '\\u003c');
    out = out.replace('<script>', () => `<script>window.cora={onData:function(f){f(${data})}};</script><script>`);
  }
  writeFileSync(process.argv[2], out);
}
console.log('page', Math.round(page.length / 1024), 'KB; echarts', Math.round(js.length / 1024), 'KB');
